import { initSimnet } from '@hirosystems/clarinet-sdk';
import { Cl } from '@stacks/transactions';
import assert from 'node:assert/strict';
const simnet = await initSimnet('./Clarinet.toml');
const A = simnet.getAccounts(), dep = A.get('deployer'), w1 = A.get('wallet_1');
let fails = 0; const chk = (c, m) => { console.log((c ? 'ok   ' : 'FAIL ') + m); if (!c) fails++; };
const root = Cl.bufferFromHex('ab'.repeat(32)), root2 = Cl.bufferFromHex('cd'.repeat(32));
let r = simnet.callPublicFn('fairplay-board', 'seal-week', [Cl.uint(42), root, Cl.uint(25), Cl.uint(51900)], w1);
chk(JSON.stringify(r.result) === JSON.stringify(Cl.error(Cl.uint(100))), 'a stranger cannot seal: ' + Cl.prettyPrint(r.result));
r = simnet.callPublicFn('fairplay-board', 'seal-week', [Cl.uint(42), root, Cl.uint(0), Cl.uint(0)], dep);
chk(Cl.prettyPrint(r.result) === '(err u102)', 'empty week refused: ' + Cl.prettyPrint(r.result));
r = simnet.callPublicFn('fairplay-board', 'seal-week', [Cl.uint(42), root, Cl.uint(25), Cl.uint(51900)], dep);
chk(Cl.prettyPrint(r.result) === '(ok true)', 'owner seals week 42: ' + Cl.prettyPrint(r.result));
chk(r.events.some(e => e.event === 'print_event'), 'prints a seal-week event');
r = simnet.callPublicFn('fairplay-board', 'seal-week', [Cl.uint(42), root2, Cl.uint(25), Cl.uint(99999)], dep);
chk(Cl.prettyPrint(r.result) === '(err u101)', 'sealed week can never be overwritten, even by the owner: ' + Cl.prettyPrint(r.result));
r = simnet.callReadOnlyFn('fairplay-board', 'get-week', [Cl.uint(42)], w1);
chk(/root: 0xabab/.test(Cl.prettyPrint(r.result)) && /top-score: u51900/.test(Cl.prettyPrint(r.result)), 'anyone reads it: ' + Cl.prettyPrint(r.result));
chk(Cl.prettyPrint(simnet.callReadOnlyFn('fairplay-board', 'check-week', [Cl.uint(42), root], w1).result) === 'true', 'check-week true for the right fingerprint');
chk(Cl.prettyPrint(simnet.callReadOnlyFn('fairplay-board', 'check-week', [Cl.uint(42), root2], w1).result) === 'false', 'check-week false for a wrong one');
chk(Cl.prettyPrint(simnet.callReadOnlyFn('fairplay-board', 'check-week', [Cl.uint(7), root], w1).result) === 'false', 'check-week false for an unsealed week');
chk(Cl.prettyPrint(simnet.callReadOnlyFn('fairplay-board', 'get-week', [Cl.uint(7)], w1).result) === 'none', 'unsealed week is none');
simnet.mineEmptyBurnBlocks(3);
r = simnet.callReadOnlyFn('fairplay-board', 'bitcoin-block-hash', [Cl.uint(1)], w1);
chk(/^\(some 0x[0-9a-f]{64}\)$/.test(Cl.prettyPrint(r.result)), 'reads a Bitcoin block hash: ' + Cl.prettyPrint(r.result));
console.log(fails ? 'FAILED ' + fails : 'ALL PASS');
